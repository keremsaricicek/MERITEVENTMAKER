"""Synthetic CAD-like vector PDFs, for the vector-geometry path.

A layout from training/synth.py drawn as PDF drawing commands instead of
pixels: every table is a real circle or rectangle path, every chair a small
rectangle, numbers are text objects, walls are lines. It tests the GENERIC
path from a vector PDF to object proposals (src/plan-vector-objects.js). It is
not a real CAD export: there is no real CAD PDF in the repository, and the
validation against one stays open (benchmarks/plan-understanding/NEW-VENUES.md).

    python training/synth_pdf.py --out DIR --count 6 --seed 5

Writes DIR/<id>.pdf and DIR/<id>.json. The JSON is in the repository's
annotation schema, in PDF points (y down), with `source.units: "pdf-points"`.
"""
import argparse
import json
import math
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import synth  # noqa: E402


def circle_path(cx, cy, r):
    k = 0.5523 * r
    return (f"{cx + r:.2f} {cy:.2f} m "
            f"{cx + r:.2f} {cy + k:.2f} {cx + k:.2f} {cy + r:.2f} {cx:.2f} {cy + r:.2f} c "
            f"{cx - k:.2f} {cy + r:.2f} {cx - r:.2f} {cy + k:.2f} {cx - r:.2f} {cy:.2f} c "
            f"{cx - r:.2f} {cy - k:.2f} {cx - k:.2f} {cy - r:.2f} {cx:.2f} {cy - r:.2f} c "
            f"{cx + k:.2f} {cy - r:.2f} {cx + r:.2f} {cy - k:.2f} {cx + r:.2f} {cy:.2f} c h")


def rect_path(cx, cy, w, h, deg):
    a = math.radians(deg)
    c, s = math.cos(a), math.sin(a)
    pts = [(-w / 2, -h / 2), (w / 2, -h / 2), (w / 2, h / 2), (-w / 2, h / 2)]
    pts = [(cx + x * c - y * s, cy + x * s + y * c) for x, y in pts]
    return f"{pts[0][0]:.2f} {pts[0][1]:.2f} m " + " ".join(f"{x:.2f} {y:.2f} l" for x, y in pts[1:]) + " h"


def write_pdf(path, W, H, ops):
    # PDF y is up; the layout is y down. Flip once with the CTM.
    content = f"1 0 0 -1 0 {H} cm\n" + "\n".join(ops)
    objs = [
        "<< /Type /Catalog /Pages 2 0 R >>",
        "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {W} {H}] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
        f"<< /Length {len(content.encode())} >>\nstream\n{content}\nendstream",
        "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    out = "%PDF-1.4\n"
    offs = []
    for i, o in enumerate(objs, 1):
        offs.append(len(out.encode()))
        out += f"{i} 0 obj\n{o}\nendobj\n"
    xref = len(out.encode())
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n" + "".join(f"{o:010d} 00000 n \n" for o in offs)
    out += f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n"
    open(path, "wb").write(out.encode("latin-1"))


def text_op(x, y, s, size):
    # text is drawn in the flipped frame, so flip it back locally
    return f"BT /F1 {size:.1f} Tf 1 0 0 -1 {x:.2f} {y:.2f} Tm ({s}) Tj ET"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--count", type=int, default=6)
    ap.add_argument("--seed", type=int, default=5)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    for i in range(a.count):
        fam = [0, 4, 9][i % 3]  # line-drawing families: CAD-like
        img, p, meta = synth.draw_plan(a.seed * 1000 + i, fam, gen=1)
        W, H = img.width, img.height
        scale = 0.6  # layout px -> PDF points
        ops = ["0 0 0 RG 1 w"]
        m = 20
        ops.append(f"{m} {m} m {W * scale - m} {m} l {W * scale - m} {H * scale - m} l {m} {H * scale - m} l h S")
        objs = []
        for o in p.objects:
            cx, cy, w, h = o["cx"] * scale, o["cy"] * scale, o["w"] * scale, o["h"] * scale
            if o["class"] == "table":
                ops.append(circle_path(cx, cy, w / 2) + " S" if o.get("type") == "round" else rect_path(cx, cy, w, h, o.get("rotation", 0)) + " S")
                if "number" in o:
                    ops.append(text_op(cx - 3.2 * len(str(o["number"])), cy + 3, str(o["number"]), 9))
            elif o["class"] == "chair":
                ops.append(rect_path(cx, cy, w, h, o.get("rotation", 0)) + " S")
            elif o["class"] in ("stage", "bar", "column"):
                ops.append(rect_path(cx, cy, w, h, 0) + (" f" if o["class"] == "column" else " S"))
            objs.append(dict(o, cx=round(cx, 2), cy=round(cy, 2), w=round(w, 2), h=round(h, 2)))
        pid = f"vec-{synth.FAMILIES[fam]['name']}-{a.seed}-{i}"
        write_pdf(os.path.join(a.out, pid + ".pdf"), round(W * scale), round(H * scale), ops)
        ann = {"planId": pid, "source": {"file": pid + ".pdf", "width": round(W * scale), "height": round(H * scale), "units": "pdf-points", "synthetic": True, "venue": f"synthetic-vector:{synth.FAMILIES[fam]['name']}"},
               "annotationMethod": "generated by training/synth_pdf.py: exact by construction", "verification": "synthetic-exact",
               "objects": objs, "relationships": p.rels, "logicalGroups": p.groups}
        json.dump(ann, open(os.path.join(a.out, pid + ".json"), "w"))
    print(f"wrote {a.count} vector PDFs to {a.out}")


if __name__ == "__main__":
    main()
