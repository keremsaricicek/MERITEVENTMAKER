def cap_crumple(img, objs, rng, meta):
    W, H = img.size
    g = npr(rng)
    amp = rng.uniform(3, 9) * max(W, H) / 2000
    gx, gy = rng.randint(3, 6), rng.randint(3, 6)
    small = g.normal(0, 1, (2, gy, gx)).astype(np.float32)
    dx = np.asarray(Image.fromarray(small[0]).resize((W, H), Image.BICUBIC)) * amp
    dy = np.asarray(Image.fromarray(small[1]).resize((W, H), Image.BICUBIC)) * amp
    yy, xx = np.mgrid[0:H, 0:W].astype(np.float32)
    sx, sy = np.clip(xx - dx, 0, W - 1), np.clip(yy - dy, 0, H - 1)
    a = np.asarray(img, dtype=np.float32)
    x0, y0 = np.floor(sx).astype(int), np.floor(sy).astype(int)
    x1, y1 = np.minimum(x0 + 1, W - 1), np.minimum(y0 + 1, H - 1)
    fx, fy = (sx - x0)[..., None], (sy - y0)[..., None]
    out = a[y0, x0] * (1 - fx) * (1 - fy) + a[y0, x1] * fx * (1 - fy) + a[y1, x0] * (1 - fx) * fy + a[y1, x1] * fx * fy
    shade = 1 + (np.gradient(dx, axis=1) + np.gradient(dy, axis=0))[..., None] * rng.uniform(1.5, 4.0)
    out = out * np.clip(shade, 0.8, 1.08)
    for _ in range(rng.randint(1, 4)):  # creases
        if rng.random() < 0.5:
            x = rng.randint(int(W * 0.15), int(W * 0.85)); out[:, max(0, x - 1):x + 2] *= rng.uniform(0.85, 0.94)
        else:
            y = rng.randint(int(H * 0.15), int(H * 0.85)); out[max(0, y - 1):y + 2] *= rng.uniform(0.85, 0.94)
    img = Image.fromarray(np.clip(out, 0, 255).astype(np.uint8))

    def f(pts):
        ix = np.clip(pts[:, 0].round().astype(int), 0, W - 1)
        iy = np.clip(pts[:, 1].round().astype(int), 0, H - 1)
        return np.stack([pts[:, 0] + dx[iy, ix], pts[:, 1] + dy[iy, ix]], axis=1)
    meta["crumple"] = {"amp": round(amp, 2)}
    img, objs = (img, map_fn(objs, f))
    if rng.random() < 0.6:
        return L.photographed(img, objs, rng, meta)
    return jpeg(img, rng.randint(60, 90)), objs


def cap_photo2(img, objs, rng, meta):
    W, H = img.size
    m = rng.uniform(0.06, 0.15)
    j = lambda: rng.uniform(0.0, m)
    pad = rng.uniform(0.03, 0.1)
    PW, PH = int(W * (1 + 2 * pad)), int(H * (1 + 2 * pad))
    dst = [(PW * j() + W * pad, PH * j() + H * pad), (PW - PW * j() - W * pad, PH * j() + H * pad),
           (PW - PW * j() - W * pad, PH - PH * j() - H * pad), (PW * j() + W * pad, PH - PH * j() - H * pad)]
    Hm = L.homography([(0, 0), (W, 0), (W, H), (0, H)], dst)
    Hinv = np.linalg.inv(Hm)
    desk = rng.choice([(92, 72, 54), (150, 130, 110), (60, 62, 66), (200, 196, 188), (120, 96, 70)])
    img = img.transform((PW, PH), Image.PERSPECTIVE, tuple((Hinv / Hinv[2, 2]).flatten()[:8]), resample=Image.BICUBIC, fillcolor=desk)
    objs = L.map_objects(objs, Hm)
    a = np.asarray(img, dtype=np.float32)
    g = npr(rng)
    yy, xx = np.mgrid[0:PH, 0:PW]
    r2 = ((xx / PW - 0.5) ** 2 + (yy / PH - 0.5) ** 2) / 0.5
    a = a * (1 - rng.uniform(0.15, 0.45) * r2)[..., None]
    cast = np.array(rng.choice([(1.06, 1.0, 0.86), (0.9, 0.97, 1.08), (1.0, 1.0, 1.0), (1.04, 1.02, 0.92)]), np.float32)
    a = a * cast * rng.uniform(0.85, 1.05)
    gx, gy = rng.uniform(-1, 1), rng.uniform(-1, 1)
    a = a * (1 - rng.uniform(0.05, 0.3) * np.clip(gx * (xx / PW - 0.5) + gy * (yy / PH - 0.5) + 0.5, 0, 1))[..., None]
    a = a + g.normal(0, rng.uniform(2, 7), a.shape)
    img = Image.fromarray(np.clip(a, 0, 255).astype(np.uint8))
    if rng.random() < 0.5:  # motion blur
        k = rng.choice([3, 5])
        ker = [0] * (k * k)
        horiz = rng.random() < 0.5
        for i in range(k):
            ker[(k // 2) * k + i if horiz else i * k + k // 2] = 1
        img = img.filter(ImageFilter.Kernel((k, k), ker, scale=k))
        meta["motionBlur"] = k
    else:
        img = img.filter(ImageFilter.GaussianBlur(rng.uniform(0.6, 1.8)))
    if rng.random() < 0.5:  # downscaled by the phone app
        s = rng.uniform(0.55, 0.85)
        w, h = int(PW * s), int(PH * s)
        img = img.resize((w, h), Image.BILINEAR)
        objs = L.map_objects(objs, np.diag([w / PW, h / PH, 1.0]))
    meta["photo2"] = {"margin": round(m, 3)}
    return jpeg(img, rng.randint(30, 70)), objs


def cap_fax(img, objs, rng, meta):
    """HELD OUT (exam only): a fax / 1-bit low-dpi copy with streaks."""
    W, H = img.size
    s = rng.uniform(0.45, 0.65)
    w, h = int(W * s), int(H * s)
    a = np.asarray(img.convert("L").resize((w, h), Image.BILINEAR), dtype=np.float32)
    g = npr(rng)
    a = a + g.normal(0, 12, a.shape)
    b = np.where(a < rng.uniform(150, 200), 0, 255).astype(np.float32)
    for _ in range(rng.randint(2, 10)):
        y = rng.randint(0, h - 1)
        b[y:y + rng.randint(1, 3)] = rng.choice([0, 255]) if rng.random() < 0.3 else 255
    img = Image.fromarray(b.astype(np.uint8)).convert("RGB")
    meta["fax"] = {"scale": round(s, 3)}
    return img, L.map_objects(objs, np.diag([w / W, h / H, 1.0]))


def capture7(big, W, H, objs, rng, meta, style, mode):
    meta["capture"] = mode
    if mode == "vector":
        return cap_vector(big, W, H, objs, rng, meta)
    img = big.resize((W, H), Image.LANCZOS)
    if mode in ("clean", "scan", "photo", "turned"):
        if mode == "clean":
            return img, objs
        if mode == "scan":
            return (L.page_scan if style == "G" else L.scanned)(img, objs, rng, meta)
        if mode == "photo":
            if style == "P" or rng.random() < 0.4:
                img = S6.fold(img, rng, meta)
            if rng.random() < 0.35:
                img, objs = S6.turn(img, objs, rng, meta, (90, 270))
            return L.photographed(img, objs, rng, meta)
        img, objs = S6.turn(img, objs, rng, meta)
        return L.scanned(img, objs, rng, meta)
    if rng.random() < 0.25 and mode in ("faded", "copy", "photo2", "fax"):
        img, objs = S6.turn(img, objs, rng, meta)
    if mode == "faded":
        return cap_faded(img, objs, rng, meta)
    if mode == "copy":
        return cap_copy(img, objs, rng, meta)
    if mode == "screenshot":
        return cap_screenshot(img, objs, rng, meta)
    if mode == "crumple":
        return cap_crumple(img, objs, rng, meta)
    if mode == "photo2":
        if rng.random() < 0.4:
            img = S6.fold(img, rng, meta)
        return cap_photo2(img, objs, rng, meta)
    if mode == "fax":
        return cap_fax(img, objs, rng, meta)
    raise KeyError(mode)


