def hall_shape(p, rng, hall, wall_lw):
    """L-shaped hall or a cut corner (the cut area is outside the room: blank, reserved)."""
    x0, y0, x1, y1 = hall
    fam = p.fam
    k = rng.random()
    if k < 0.18:
        cw, ch = (x1 - x0) * rng.uniform(0.15, 0.3), (y1 - y0) * rng.uniform(0.18, 0.35)
        corner = rng.choice(["tl", "tr", "bl", "br"])
        cx0 = x0 if corner[1] == "l" else x1 - cw
        cy0 = y0 if corner[0] == "t" else y1 - ch
        ext = max(6, int(min(p.w, p.h) * 0.01)) + wall_lw
        p.d.rectangle([(cx0 - (ext if corner[1] == "l" else 0)) * SS, (cy0 - (ext if corner[0] == "t" else 0)) * SS,
                       (cx0 + cw + (ext if corner[1] == "r" else 0)) * SS, (cy0 + ch + (ext if corner[0] == "b" else 0)) * SS], fill=fam["paper"])
        ix = cx0 + cw if corner[1] == "l" else cx0
        iy = cy0 + ch if corner[0] == "t" else cy0
        ox = x0 if corner[1] == "l" else x1
        oy = y0 if corner[0] == "t" else y1
        p.d.line([(ox * SS, iy * SS), (ix * SS, iy * SS), (ix * SS, oy * SS)], fill=fam["line"], width=wall_lw * SS)
        p.take((cx0 - 4, cy0 - 4, cx0 + cw + 4, cy0 + ch + 4))
        return "L"
    if k < 0.3:
        c = min(x1 - x0, y1 - y0) * rng.uniform(0.08, 0.18)
        corner = rng.choice(["tl", "tr", "bl", "br"])
        X = x0 if corner[1] == "l" else x1
        Y = y0 if corner[0] == "t" else y1
        sx = 1 if corner[1] == "l" else -1
        sy = 1 if corner[0] == "t" else -1
        ext = max(6, int(min(p.w, p.h) * 0.01)) + wall_lw
        p.poly([(X - sx * ext, Y - sy * ext), (X + sx * c, Y - sy * ext), (X - sx * ext, Y + sy * c)], fam["paper"], None, 1)
        p.d.line([((X + sx * c) * SS, Y * SS), (X * SS, (Y + sy * c) * SS)], fill=fam["line"], width=wall_lw * SS)
        p.take((min(X, X + sx * c) - 2, min(Y, Y + sy * c) - 2, max(X, X + sx * c) + 2, max(Y, Y + sy * c) + 2))
        return "cut"
    return "rect"


def windows(p, rng, hall):
    x0, y0, x1, y1 = hall
    line = p.fam["line"]
    for _ in range(rng.randint(0, 6)):
        side = rng.choice(["top", "bottom", "left", "right"])
        t, L_ = rng.uniform(0.1, 0.85), rng.uniform(0.05, 0.12)
        if side in ("top", "bottom"):
            y = y0 if side == "top" else y1
            a, b = x0 + t * (x1 - x0), x0 + (t + L_) * (x1 - x0)
            p.d.rectangle([a * SS, (y - 3) * SS, b * SS, (y + 3) * SS], fill=(255, 255, 255), outline=line, width=SS)
            p.d.line([(a * SS, y * SS), (b * SS, y * SS)], fill=line, width=SS)
        else:
            x = x0 if side == "left" else x1
            a, b = y0 + t * (y1 - y0), y0 + (t + L_) * (y1 - y0)
            p.d.rectangle([(x - 3) * SS, a * SS, (x + 3) * SS, b * SS], fill=(255, 255, 255), outline=line, width=SS)
            p.d.line([(x * SS, a * SS), (x * SS, b * SS)], fill=line, width=SS)


