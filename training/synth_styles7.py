def ckinds(p, rng):
    ks = p.fam.get("chairs7") or [p.fam["chair"]]
    main = rng.choice(ks)
    rnd = p.fam.get("round_chair") if rng.random() < 0.5 and p.fam.get("round_chair") else rng.choice(ks)
    mix = rng.random() < 0.2
    return (lambda: rng.choice(ks)) if mix else (lambda: main), (lambda: rng.choice(ks)) if mix else (lambda: rnd)


def dot_on(p, rng):
    return p.fam.get("centre_dot") and rng.random() < p.fam.get("dot_p", 0.9)


def gala_item(p, rng, kind, cx, cy, unit, sq, rd, tuck_p=0.15):
    deg = rng.choice([0, 0, 90]) if rng.random() < 0.85 else rng.choice([15, 30, 45, -20, -35, 60])
    tuck = rng.random() < tuck_p
    if kind == "round":
        r = unit * rng.uniform(0.7, 1.05)
        return p.round7(cx, cy, r, rng.choice([5, 6, 8, 8, 10, 10, 12]), rd(), tuck=tuck, dot=dot_on(p, rng))
    if kind == "oval":
        a = unit * rng.uniform(1.1, 1.7)
        return p.oval7(cx, cy, a, a * rng.uniform(0.5, 0.7), deg, rng.choice([6, 8, 10, 12]), rd(), tuck=tuck, dot=dot_on(p, rng))
    if kind == "square":
        s = unit * rng.uniform(0.8, 1.15)
        return p.rect7(cx, cy, s, s, deg, rng.choice([1, 1, 2]), rng.choice([0, 1]), sq(), tuck=tuck, dots=1 if dot_on(p, rng) else 0)
    if kind == "rect":
        s = unit * rng.uniform(0.8, 1.0)
        k = rng.choice([2, 3, 3, 4])
        return p.rect7(cx, cy, s * k * 0.75, s, deg, k, rng.choice([0, 1]), sq(), tuck=tuck, dots=2 if dot_on(p, rng) else 0)
    if kind == "long":
        s = unit * rng.uniform(0.75, 0.95)
        k = rng.randint(4, 10)
        return p.rect7(cx, cy, s * k * 0.8, s, deg, k, rng.choice([0, 1, 1]), sq(), dots=rng.choice([2, 3]) if dot_on(p, rng) else 0)
    if kind == "merged":
        return p.merged7(cx, cy, rng.choice([2, 3, 3, 4, 5]), unit * rng.uniform(0.8, 1.05), deg if deg in (0, 90) else 0, sq(), dot_on(p, rng))
    if kind == "cocktail":
        r = unit * rng.uniform(0.3, 0.45)
        stools = rng.choice([0, 0, 0, 2, 3, 4])
        tid = p.round7(cx, cy, r, stools, rng.choice(["dot", "ring", "circle"]) if stools else None, typ="bistro")
        return tid
    raise KeyError(kind)


def scatter(p, rng, box, unit, kinds, weights, n, sq, rd, tuck_p=0.15):
    """A jittered grid (event rooms are filled, not sprinkled), then random fill-in up to n."""
    x0, y0, x1, y1 = box
    placed = 0
    pitch = unit * rng.uniform(3.4, 4.2)
    stagger = rng.random() < 0.4
    for row, y in enumerate(np.arange(y0 + pitch * 0.55, y1 - unit * 0.6, pitch)):
        for x in np.arange(x0 + pitch * 0.55 + (pitch / 2 if stagger and row % 2 else 0), x1 - unit * 0.6, pitch):
            if placed >= n or rng.random() > 0.88:
                continue
            kind = rng.choices(kinds, weights=weights)[0]
            if gala_item(p, rng, kind, x + rng.uniform(-0.12, 0.12) * pitch, y + rng.uniform(-0.12, 0.12) * pitch, unit, sq, rd, tuck_p):
                placed += 1
    for _ in range(max(0, n - placed) * 3):
        if placed >= n:
            break
        kind = rng.choices(kinds, weights=weights)[0]
        cx, cy = rng.uniform(x0 + unit, x1 - unit), rng.uniform(y0 + unit, y1 - unit)
        if gala_item(p, rng, kind, cx, cy, unit, sq, rd, tuck_p):
            placed += 1


def theatre_rows7(p, rng, box, unit, facing, kind):
    x0, y0, x1, y1 = box
    cs = unit * rng.uniform(0.5, 0.72)
    pitch = cs * rng.uniform(1.12, 1.45)
    row_p = pitch * rng.uniform(1.3, 1.8)
    curved = p.style == "G" and rng.random() < 0.4
    letters = rng.random() < 0.5
    horiz_rows = facing in (-90, 90)
    rows = np.arange((y0 if horiz_rows else x0) + row_p, (y1 if horiz_rows else x1) - row_p / 2, row_p)
    span = (x0, x1) if horiz_rows else (y0, y1)
    gap_at = rng.uniform(0.35, 0.65) if rng.random() < 0.6 else None
    for ri, rv in enumerate(rows):
        for t in np.arange(span[0] + pitch, span[1] - pitch / 2, pitch):
            f = (t - span[0]) / (span[1] - span[0])
            if gap_at and abs(f - gap_at) < pitch / (span[1] - span[0]) * 0.9:
                continue
            bend = (math.cos((f - 0.5) * math.pi) - 1) * unit * 1.2 if curved else 0
            xx, yy = (t, rv + bend * (1 if facing == -90 else -1)) if horiz_rows else (rv + bend * (1 if facing == 180 else -1), t)
            b = (xx - cs / 2, yy - cs / 2, xx + cs / 2, yy + cs / 2)
            if p.free(b, pad=1):
                p.take(b)
                ang = facing + ((f - 0.5) * 30 if curved else 0)
                p.chair(xx, yy, cs, ang, None, kind=kind)
        if letters:
            s = chr(65 + ri % 26)
            lx, ly = (span[0] + pitch * 0.2, rv) if horiz_rows else (rv, span[0] + pitch * 0.2)
            tb = (lx - cs * 0.4, ly - cs * 0.4, lx + cs * 0.4, ly + cs * 0.4)
            if p.free(tb, pad=0):
                p.take(tb)
                p.text(lx, ly, s, cs * 0.6, fill=(80, 80, 80))
                rec(p, "text", lx, ly, cs * 0.8, cs * 0.8, s)


