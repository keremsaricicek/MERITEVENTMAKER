def map_fn(objs, f):
    out = []
    for o in objs:
        corners = rot_pts([(o["cx"] - o["w"] / 2, o["cy"] - o["h"] / 2), (o["cx"] + o["w"] / 2, o["cy"] - o["h"] / 2),
                           (o["cx"] + o["w"] / 2, o["cy"] + o["h"] / 2), (o["cx"] - o["w"] / 2, o["cy"] + o["h"] / 2)], o["cx"], o["cy"], o.get("rotation", 0))
        pts = f(np.array(corners, float))
        c = pts.mean(axis=0)
        w = (np.linalg.norm(pts[1] - pts[0]) + np.linalg.norm(pts[2] - pts[3])) / 2
        h = (np.linalg.norm(pts[3] - pts[0]) + np.linalg.norm(pts[2] - pts[1])) / 2
        deg = math.degrees(math.atan2(pts[1][1] - pts[0][1], pts[1][0] - pts[0][0]))
        n = dict(o, cx=round(float(c[0]), 1), cy=round(float(c[1]), 1), w=round(float(w), 1), h=round(float(h), 1), rotation=round(deg % 360, 1))
        n["_corners"] = pts.tolist()
        out.append(n)
    return out


def jpeg(img, q):
    buf = io.BytesIO()
    img.save(buf, "JPEG", quality=int(q))
    return Image.open(io.BytesIO(buf.getvalue())).convert("RGB")


def npr(rng):
    return np.random.default_rng(rng.randint(0, 1 << 30))


def cap_vector(big, W, H, objs, rng, meta):
    if rng.random() < 0.5:  # crisp, box-filtered, slight sharpening: a PDF page rendered at its size
        img = big.resize((W, H), Image.BOX).filter(ImageFilter.UnsharpMask(radius=1, percent=60, threshold=2))
        meta["vector"] = "crisp"
        return img, objs
    s = rng.uniform(0.55, 0.85)  # rendered without anti-aliasing, at a lower size
    w, h = int(W * s), int(H * s)
    img = big.resize((w, h), Image.NEAREST)
    meta["vector"] = {"aliased": round(s, 3)}
    return img, L.map_objects(objs, np.diag([w / W, h / H, 1.0]))


def cap_faded(img, objs, rng, meta):
    a = np.asarray(img, dtype=np.float32)
    k = rng.uniform(0.4, 0.75)
    a = 255 - (255 - a) * k
    cast = np.array(rng.choice([(1.0, 0.98, 0.9), (1.0, 0.97, 0.94), (0.97, 0.99, 1.0), (1.0, 1.0, 1.0)]), np.float32)
    a = a * cast
    H, W = a.shape[:2]
    g = npr(rng)
    for _ in range(rng.randint(0, 6)):  # toner streaks (lighter vertical bands)
        x, wd = rng.randint(0, W - 1), rng.randint(2, max(3, W // 60))
        a[:, x:x + wd] = 255 - (255 - a[:, x:x + wd]) * rng.uniform(0.3, 0.7)
    a = a + g.normal(0, rng.uniform(1, 4), a.shape)
    img = Image.fromarray(np.clip(a, 0, 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(rng.uniform(0.3, 0.8)))
    meta["faded"] = round(k, 3)
    return jpeg(img, rng.randint(55, 88)), objs


def cap_copy(img, objs, rng, meta):
    a = np.asarray(img.convert("L"), dtype=np.float32)
    if rng.random() < 0.3:
        a = np.asarray(img, dtype=np.float32).mean(axis=2) * 0.5 + a * 0.5
    gamma = rng.uniform(1.2, 2.0)
    a = 255 * (a / 255) ** gamma
    H, W = a.shape
    g = npr(rng)
    yy, xx = np.mgrid[0:H, 0:W]
    e = np.minimum(np.minimum(xx, W - 1 - xx), np.minimum(yy, H - 1 - yy)) / (0.06 * min(W, H))
    a = a * (0.65 + 0.35 * np.clip(e, 0, 1))
    sp = g.random(a.shape) < rng.uniform(0.0003, 0.002)
    a[sp] = g.uniform(0, 90, sp.sum())
    a = a + g.normal(0, rng.uniform(2, 6), a.shape)
    img = Image.fromarray(np.clip(a, 0, 255).astype(np.uint8)).convert("RGB")
    meta["copy"] = {"gamma": round(gamma, 2)}
    return L.scanned(img, objs, rng, meta)


