def spot(p, rng, hall, page, w, h, outside=False, tries=25):
    x0, y0, x1, y1 = hall
    W, H = page
    for _ in range(tries):
        if outside:
            if rng.random() < 0.5:
                cx = rng.uniform(w / 2 + 6, W - w / 2 - 6)
                cy = rng.choice([rng.uniform(h / 2 + 4, max(h / 2 + 5, y0 - h / 2 - 6)), rng.uniform(min(H - h / 2 - 5, y1 + h / 2 + 6), H - h / 2 - 4)])
            else:
                cy = rng.uniform(h / 2 + 6, H - h / 2 - 6)
                cx = rng.choice([rng.uniform(w / 2 + 4, max(w / 2 + 5, x0 - w / 2 - 6)), rng.uniform(min(W - w / 2 - 5, x1 + w / 2 + 6), W - w / 2 - 4)])
        else:
            cx, cy = rng.uniform(x0 + w / 2 + 8, x1 - w / 2 - 8), rng.uniform(y0 + h / 2 + 8, y1 - h / 2 - 8)
        b = (cx - w / 2, cy - h / 2, cx + w / 2, cy + h / 2)
        if p.free(b, pad=4):
            p.take(b)
            return cx, cy
    return None


def arrowhead(p, tip, back, size, colour):
    ang = math.atan2(tip[1] - back[1], tip[0] - back[0])
    pts = [tip, (tip[0] - size * math.cos(ang - 0.4), tip[1] - size * math.sin(ang - 0.4)), (tip[0] - size * math.cos(ang + 0.4), tip[1] - size * math.sin(ang + 0.4))]
    p.poly(pts, colour, colour, 1)


def grid_axes(p, rng, hall, page, unit):
    """CAD column-grid bubbles: circled letters/numbers in the margins — they look like numbered discs."""
    x0, y0, x1, y1 = hall
    W, H = page
    col = rng.choice([(90, 90, 90), (150, 60, 60), p.fam["line"]])
    r = unit * rng.uniform(0.28, 0.4)
    nx, ny = rng.randint(3, 7), rng.randint(2, 5)
    for k in range(nx):
        x = x0 + (x1 - x0) * (k + 0.5) / nx
        yb = y0 - r * 1.6
        if yb - r < 4:
            continue
        b = (x - r, yb - r, x + r, yb + r)
        if not p.free(b, pad=1):
            continue
        p.take(b)
        for yy in np.arange(y0, y1, unit * 0.6):
            p.d.line([(x * SS, yy * SS), (x * SS, (yy + unit * 0.3) * SS)], fill=(225, 225, 225), width=SS)
