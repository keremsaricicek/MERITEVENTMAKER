def dancefloor7(p, rng, box, unit, central=False):
    if not p.free(box, pad=2):
        return False
    x0, y0, x1, y1 = box
    cx, cy, dw, dh = (x0 + x1) / 2, (y0 + y1) / 2, x1 - x0, y1 - y0
    v = rng.choice(["parquet", "hatch", "circle", "plain", "checker"])
    line = p.fam["line"]
    if v == "checker":
        s = max(8, unit * rng.uniform(0.35, 0.6))
        cols = [(226, 204, 160), (196, 162, 112)] if p.style == "G" else [(232, 232, 232), (196, 196, 196)]
