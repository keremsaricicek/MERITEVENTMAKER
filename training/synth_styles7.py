def numbering7(p, rng, pattern, unit):
    tabs = [o for o in p.objects if o["class"] == "table" and o.get("type") != "bistro" and not o.get("ignore")]
    merged = {m for g in p.groups for m in g["members"]}
    tabs = [o for o in tabs if o["id"] not in merged]
    if not tabs:
        return
    tol = unit * 0.7

    def rows_of(key_a, key_b):
        xs = sorted(tabs, key=lambda o: o[key_a])
        rows, cur = [], [xs[0]]
        for o in xs[1:]:
            if abs(o[key_a] - cur[-1][key_a]) < tol:
                cur.append(o)
            else:
                rows.append(cur)
                cur = [o]
        rows.append(cur)
        return [sorted(r, key=lambda o: o[key_b]) for r in rows]
    left = []
    if pattern == "column":
        order = [o for r in rows_of("cx", "cy") for o in r]
    elif pattern in ("block", "letters"):
        mid = sorted(o["cx"] for o in tabs)[len(tabs) // 2]
        left = [o for r in rows_of("cy", "cx") for o in r if o["cx"] < mid]
        order = left + [o for r in rows_of("cy", "cx") for o in r if o["cx"] >= mid]
    else:
        order = [o for r in rows_of("cy", "cx") for o in r]
    n = rng.choice([1, 1, 1, 1, 101 if p.style == "P" else 1, 21])
    prefix = rng.choice(["T", "M", "T-", "T", "Masa "]) if pattern == "prefix" else ""
    texts = []
    nvip = rng.randint(2, 6) if pattern == "vip" else 0
    half = len(left)
    for i, o in enumerate(order):
        if pattern == "skip13" and n == 13:
            n += 1
        if pattern == "letters":
            texts.append(("A" + str(i + 1)) if i < half else ("B" + str(i - half + 1)))
            continue
        if pattern == "vip" and i < nvip:
            texts.append(f"VIP {i + 1}")
            continue
        if pattern == "padded":
            texts.append(f"{n:02d}")
        else:
            texts.append(prefix + str(n))
        n += 1
    if pattern == "padded" and rng.random() < 0.5:
        texts = ["T" + s for s in texts]
    if pattern == "insert" and len(order) > 12:
        k = rng.randint(3, len(order) - 6)
        for j in range(3):
            texts[k + j] = str(n + j)
    if pattern == "descending":
        texts = texts[::-1]
    line = p.fam["line"]
    ink = rng.choice([(40, 40, 40), (200, 60, 30), (30, 60, 150)]) if p.style == "G" else line
    for o, s in zip(order, texts):
        r = min(o["w"], o["h"]) / 2
        outside = pattern == "outside" or (p.style == "G" and rng.random() < 0.15)
        if p.style == "P" and not outside:
            if rng.random() < 0.04 and o.get("type") == "round":
                p.ellipse(o["cx"], o["cy"], r, r, (62, 62, 62), line, max(1, p.fam["lw"]))
                p.text(o["cx"], o["cy"], s, r * 0.55, fill=(78, 78, 78))
                o["numberUnreadable"] = True
                continue
            size = r * rng.uniform(0.48, 0.62)
            if len(s) == 3 and s.isdigit() and rng.random() < 0.7:
                p.text(o["cx"], o["cy"] - size * 0.5, s[:-1], size * 0.85)
                p.text(o["cx"], o["cy"] + size * 0.5, s[-1], size * 0.85)
                o["numberTwoLine"] = True
            else:
                p.text(o["cx"], o["cy"], s, size / max(1, (len(s) - 2) * 0.35 + 1) if len(s) > 2 else size)
        elif outside:
            size = max(9, unit * rng.uniform(0.28, 0.4))
            for _ in range(6):
                t = rng.uniform(0, 2 * math.pi)
                d = max(o["w"], o["h"]) / 2 + size * 0.9 + (unit * 0.45 if o.get("seats") else 0)
                tx, ty = o["cx"] + d * math.cos(t), o["cy"] + d * math.sin(t)
                tw = size * 0.62 * len(s) + 6
                b = (tx - tw / 2, ty - size * 0.75, tx + tw / 2, ty + size * 0.75)
                if p.free(b, pad=1):
                    break
            else:
                continue
            p.take(b)
            if rng.random() < 0.5:
                p.d.ellipse([v * SS for v in (tx - max(tw / 2, size), ty - max(tw / 2, size), tx + max(tw / 2, size), ty + max(tw / 2, size))] if len(s) <= 2 else
                            [v * SS for v in b], fill=(255, 255, 255), outline=line, width=SS)
            else:
                p.d.rounded_rectangle([v * SS for v in b], radius=3 * SS, fill=(255, 255, 255), outline=line, width=SS)
            p.text(tx, ty, s, size, fill=ink)
            o["numberPlacement"] = "tag"
        else:
            size = max(9, r * rng.uniform(0.5, 0.72)) / max(1, (len(s) - 2) * 0.3 + 1)
            p.text(o["cx"], o["cy"] - (r * 0.35 if o.get("type") in ("square", "round") else 0), s, size, fill=ink)
        o["numberText"] = s
        if s.isdigit():
            o["number"] = int(s)


