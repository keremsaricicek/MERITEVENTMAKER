"""Package a trained run as a versioned, pinned model the app can load.

    python training/package.py --run runs/vN --version vN [--activate]

Writes models/plan-detector/<version>/:
  model.js       the ONNX bytes as base64 in a script (a page opened from disk
                 can run a script beside it but cannot fetch a file)
  manifest.json  what it is, what it was trained on, the sha256 and size of
                 the bytes, and the measured results that were in the run
                 directory. Nothing is filled in that was not measured.

--activate rewrites the PIN in src/plan-model.js to this version. Activation is
a commit, so rolling back is reverting it (the previous version's files stay
in models/plan-detector/).
"""
import argparse
import base64
import hashlib
import json
import os
import re
import subprocess

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--version", required=True)
    ap.add_argument("--activate", action="store_true")
    ap.add_argument("--models-dir", default=os.path.join(REPO, "models", "plan-detector"),
                    help="where versions are written (a test writes a throwaway version elsewhere)")
    a = ap.parse_args()
    onnx = os.path.join(a.run, "model.onnx")
    data = open(onnx, "rb").read()
    sha = hashlib.sha256(data).hexdigest()
    out = os.path.join(a.models_dir, a.version)
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "model.js"), "w") as f:
        f.write("// GENERATED by training/package.py — the plan-symbol detector " + a.version + " as base64.\n")
        f.write("// Pinned by size and sha256 in src/plan-model.js; a file that does not match is refused.\n")
        f.write("globalThis.MERIT_PLAN_MODEL_EMBED=" + json.dumps({"version": a.version, "b64": base64.b64encode(data).decode()}) + ";\n")
    ck = {}
    try:
        import torch
        ck = torch.load(os.path.join(a.run, "model.pt"), map_location="cpu", weights_only=False)
    except Exception as e:  # the manifest says it could not read it rather than inventing values
        ck = {"error": str(e)}
    def strip_paths(v):
        # An absolute path on the training machine says nothing about the model.
        if isinstance(v, str) and os.path.isabs(v):
            return os.path.basename(v.rstrip("/"))
        if isinstance(v, dict):
            return {k: strip_paths(x) for k, x in v.items()}
        if isinstance(v, list):
            return [strip_paths(x) for x in v]
        return v
    evals = {}
    for f in sorted(os.listdir(a.run)):
        if f.startswith("eval") and f.endswith(".json"):
            evals[f] = strip_paths(json.load(open(os.path.join(a.run, f))))
    commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=REPO, capture_output=True, text=True).stdout.strip()
    args = dict(ck.get("args") or {})
    real = [r for r in str(args.get("real") or "").split(",") if r]
    held = str(args.get("exclude_families") or "")
    trained_on = ("synthetic banquet plans (training/synth.py" + (f", styles other than {held}" if held else "") + ")"
                  + (" plus the real venue(s) " + ", ".join(real) if real else " only; no real plan"))
    # Paths on the training machine say nothing about the model and leak a
    # directory layout; keep the file names only.
    args = strip_paths(args)
    manifest = {
        "id": "merit-plan-detector", "version": a.version, "bytes": len(data), "sha256": sha,
        "format": "ONNX opset 17, input image[1,1,H,W] grey 0..1 (H,W multiples of 16), outputs heat[1,4,H/4,W/4] (sigmoid), size[1,2,..] log(w/4),log(h/4), offset[1,2,..]",
        "classes": ["table_round", "table_rect", "chair", "column"],
        "trainedModel": True,
        "domain": "plan symbols only: tables, chairs, columns. Not rooms, not numbers, not capacity.",
        "training": {"args": args, "steps": ck.get("step"), "params": ck.get("params"), "commitAtPackaging": commit,
                     "data": trained_on},
        "measured": evals,
        "thresholds": json.load(open(os.path.join(a.run, "thresholds.json"))) if os.path.exists(os.path.join(a.run, "thresholds.json")) else None,
        "notes": "Its new-venue quality is the cross-venue folds in benchmarks/offline-intelligence/, not its score on plans it was trained on.",
    }
    json.dump(manifest, open(os.path.join(out, "manifest.json"), "w"), indent=1)
    print(f"packaged {a.version}: {len(data)} bytes, sha256 {sha}")
    if a.activate and os.path.abspath(a.models_dir) != os.path.join(REPO, "models", "plan-detector"):
        raise SystemExit("--activate pins a version in the repository; it cannot point at files outside models/plan-detector")
    if a.activate:
        p = os.path.join(REPO, "src", "plan-model.js")
        s = open(p).read()
        # Found-or-refuse by search, not by "did the text change": activating
        # the version that is already pinned changes nothing and is not an error.
        pin_re = r'version: "[^"]*",\n    file: "[^"]*",\n    bytes: \d+,\n    sha256: "[^"]*",'
        if not re.search(pin_re, s):
            raise SystemExit("could not find the PIN block in src/plan-model.js")
        s2 = re.sub(pin_re, f'version: "{a.version}",\n    file: "models/plan-detector/{a.version}/model.js",\n    bytes: {len(data)},\n    sha256: "{sha}",', s, count=1)
        tj = os.path.join(a.run, "thresholds.json")
        if os.path.exists(tj):
            thr = {k: v["threshold"] for k, v in json.load(open(tj))["perClass"].items()}
            if not re.search(r"thresholds: \{[^}]*\},", s2):
                raise SystemExit("could not find the thresholds in src/plan-model.js")
            s2 = re.sub(r"thresholds: \{[^}]*\},", "thresholds: { " + ", ".join(f"{k}: {v}" for k, v in thr.items()) + " },", s2, count=1)
        if not re.search(r'trainedOn: "[^"]*",', s2):
            raise SystemExit("could not find trainedOn in src/plan-model.js")
        s2 = re.sub(r'trainedOn: "[^"]*",', lambda m: "trainedOn: " + json.dumps(trained_on) + ",", s2, count=1)
        open(p, "w").write(s2)
        print("activated in src/plan-model.js")


if __name__ == "__main__":
    main()
