// Builds benchmarks/ux/TASKS.md from the ux-operator-tasks suite's results.
//
//   node tests/run.mjs ux-operator-tasks --all            # measures, writes tests/.artifacts/ux/results.json
//   node benchmarks/ux/make-tasks-md.mjs [artifactDir] [--before=<dir>]
//
// Every number in TASKS.md is read from results.json; nothing is typed in by
// hand. Screenshots of steps that had a problem are copied (JPEG, 1280 wide)
// to benchmarks/ux/shots/ so the paths in the table open in the repository.
// `--before=<artifactDir>` adds a before/after column for a fix.
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "../..");
const args = process.argv.slice(2);
const artifactDir = path.resolve(args.find((a) => !a.startsWith("--")) || path.join(REPO, "tests/.artifacts"));
const beforeDir = (args.find((a) => a.startsWith("--before=")) || "").slice(9);
const results = JSON.parse(fs.readFileSync(path.join(artifactDir, "ux/results.json"), "utf8"));
const before = beforeDir ? JSON.parse(fs.readFileSync(path.join(path.resolve(beforeDir), "ux/results.json"), "utf8")) : null;
const shotsDir = path.join(HERE, "shots");
fs.mkdirSync(shotsDir, { recursive: true });

const copyShot = (rel) => {
  const src = path.join(artifactDir, rel);
  const name = rel.replace(/^ux\//, "").replace(/\//g, "__").replace(/\.png$/, ".jpg");
  const dst = path.join(shotsDir, name);
  if (!fs.existsSync(dst)) execFileSync("convert", [src, "-resize", "1280x", "-quality", "62", dst]);
  return "shots/" + name;
};

const problemsOf = (step) => {
  const a = step.audit, out = [];
  if (a.overflowX > 0) out.push(`page scrolls sideways +${a.overflowX}px`);
  if (a.clipped.length) out.push(`${a.clipped.length} text cut off (${a.clipped.slice(0, 2).map((x) => `${x.el} "${x.text}"`).join("; ")})`);
  if (a.spill.length) out.push(`${a.spill.length} text spills out of its box (${a.spill.slice(0, 2).map((x) => `${x.el} "${x.text}"`).join("; ")})`);
  const under11 = a.small.filter((x) => x.px < 11);
  if (under11.length) out.push(`${under11.length} texts < 11px (smallest ${Math.min(...under11.map((x) => x.px))}px: ${under11.slice(0, 2).map((x) => `\`${x.rule}\``).join(", ")})`);
  return out;
};

const TASKS = [];
for (const run of results) for (const t of run.tasks) if (!TASKS.find((x) => x.id === t.id)) TASKS.push({ id: t.id, title: t.title });

let md = `# Operator tasks, counted\n\n`;
md += `Generated by \`benchmarks/ux/make-tasks-md.mjs\` from \`tests/suites/ux-operator-tasks.test.mjs\` (run \`node tests/run.mjs ux-operator-tasks --all\`). `;
md += `Do not edit numbers by hand.\n\n`;
md += `- **Clicks** include picking a file in the system dialog (1) and clicking into a field before typing (1). **Keys** are characters typed plus named keys (Enter, F8, Esc); a date counts 8 digits.\n`;
md += `- **Seconds** are wall-clock for the task including the app's own work (Assisted Detection, export), excluding the suite's screenshots/audits. Same-machine comparisons only.\n`;
md += `- Each step was screenshotted and audited: horizontal page scroll, text cut off (overflow hidden, no ellipsis), text spilling out of its box, text < 11px outside the plan drawing. After each task one Tab checks that keyboard focus is visible. Native browser dialogs and console errors are counted per pass.\n`;
md += `- Viewports × language: ${results.map((r) => r.combo).join(", ")}.\n\n`;

md += `## Summary\n\n| Task | ${results.map((r) => r.combo).join(" | ")} |\n|---|${results.map(() => "---").join("|")}|\n`;
for (const T of TASKS) {
  md += `| ${T.title} | ${results.map((r) => { const t = r.tasks.find((x) => x.id === T.id); return t ? `${t.ok ? "✓" : "✗"} ${t.clicks}c ${t.keys}k ${t.seconds}s` : "—"; }).join(" | ")} |\n`;
}
md += `\nc = clicks, k = keystrokes, s = seconds. ✗ = the task's outcome was not in the data (see its table).\n\n`;
md += `| Per pass | ${results.map((r) => r.combo).join(" | ")} |\n|---|${results.map(() => "---").join("|")}|\n`;
md += `| Native dialogs | ${results.map((r) => (r.nativeDialogs || []).length).join(" | ")} |\n`;
md += `| Console / page errors | ${results.map((r) => (r.errors || []).length).join(" | ")} |\n\n`;

for (const T of TASKS) {
  md += `## ${T.title}\n\n| Viewport | Clicks | Keys | Seconds | Done | Focus visible | Problems (screenshot) |\n|---|---|---|---|---|---|---|\n`;
  for (const r of results) {
    const t = r.tasks.find((x) => x.id === T.id);
    if (!t) continue;
    const b = before && (before.find((x) => x.combo === r.combo) || { tasks: [] }).tasks.find((x) => x.id === T.id);
    const problems = [];
    for (const d of t.defects || []) problems.push(`**${d}**`);
    for (const n of t.notes || []) if (!/^\{|^\[/.test(n)) problems.push(n);
    for (const s of t.steps) { const p = problemsOf(s); if (p.length) problems.push(`${s.label}: ${p.join("; ")} — [${path.basename(s.shot)}](${copyShot(s.shot)})`); }
    const was = (now, then) => (b && then !== now ? `${now} (was ${then})` : `${now}`);
    md += `| ${r.combo} | ${was(t.clicks, b && b.clicks)} | ${was(t.keys, b && b.keys)} | ${t.seconds} | ${t.ok ? "yes" : "**no**"}${b && b.ok !== t.ok ? ` (was ${b.ok ? "yes" : "no"})` : ""} | ${t.focus ? (t.focus.visible ? "yes" : t.focus.visible === false ? `**no** (${t.focus.el})` : "—") : "—"} | ${problems.join("<br>") || "none"} |\n`;
  }
  md += "\n";
}

// Small text ranked by how many screens show it.
const small = new Map();
for (const r of results) for (const t of r.tasks) for (const s of t.steps) for (const x of s.audit.small) {
  const k = x.rule;
  const e = small.get(k) || { rule: k, px: x.px, text: x.text, combos: new Set() };
  e.px = Math.min(e.px, x.px); e.combos.add(r.combo); small.set(k, e);
}
md += `## Text below 12px (outside the plan drawing), by rule\n\n| Rule (src/styles.css) | Smallest px | Example | Passes |\n|---|---|---|---|\n`;
for (const e of [...small.values()].sort((a, b) => a.px - b.px)) md += `| \`${e.rule}\` | ${e.px} | ${e.text.replace(/\|/g, "/")} | ${e.combos.size} |\n`;

fs.writeFileSync(path.join(HERE, "TASKS.md"), md);
console.log("wrote", path.join(HERE, "TASKS.md"));
