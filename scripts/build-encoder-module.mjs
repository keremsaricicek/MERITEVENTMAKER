// Generate src/plan-encoder-weights.js from the trained checkpoint.
//
//   node scripts/build-encoder-module.mjs
//
// The weights ship as a classic script that assigns a plain object, for one
// reason: the app must never fetch them. A `fetch()` for a weights file works
// in the normal build and dies in the single-file offline build, and a model
// that needs the network at runtime breaks the offline guarantee outright.
// Inlining them costs ~53KB and removes the whole class of problem.
//
// Only the weights are generated. The forward pass in src/plan-embedding.js is
// hand-written and stays put, so regenerating a checkpoint never rewrites
// executable logic.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const SRC = path.join(ROOT, "benchmarks", "embedding", "encoder-weights.json");
const OUT = path.join(ROOT, "src", "plan-encoder-weights.js");

if (!fs.existsSync(SRC)) {
  console.error(`No checkpoint at ${path.relative(ROOT, SRC)}. Run benchmarks/embedding/train-encoder.mjs.`);
  process.exit(2);
}
const w = JSON.parse(fs.readFileSync(SRC, "utf8"));

const header = `// GENERATED by scripts/build-encoder-module.mjs — do not edit by hand.
//
// Trained weights for ${w.id}: ${w.parameters} parameters, ${w.arch.embedding}-d embedding.
// ${w.licence}
// Trained ${w.trainedAt} on ${w.trainedOn.objects} objects across ${w.trainedOn.renderings.length} real renderings
// of ${w.trainedOn.plans.join(", ")}; ${w.heldOut} were held out.
//
// Inlined rather than fetched: see scripts/build-encoder-module.mjs.
`;

const body = `globalThis.MERIT_PLAN_ENCODER_WEIGHTS=${JSON.stringify({
  id: w.id, kind: w.kind, trainedModel: w.trainedModel, arch: w.arch,
  parameters: w.parameters, layers: w.layers, head: w.head,
  trainedAt: w.trainedAt, trainedOn: w.trainedOn, heldOut: w.heldOut,
  objective: w.objective, licence: w.licence, input: w.input,
})};
`;

fs.writeFileSync(OUT, header + body);
console.log(`wrote ${path.relative(ROOT, OUT)}  (${(fs.statSync(OUT).size / 1024).toFixed(0)} KB, ${w.parameters} parameters)`);
